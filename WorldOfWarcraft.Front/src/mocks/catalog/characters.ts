function withCharacterCount(sheet: PlayerSheetDto): PlayerSheetDto {
    return {
        ...sheet,
        characterCount: mockCharacters.filter((character) => character.playerPublicId === sheet.publicId).length,
    };
}

export function playerSheetByPublicId(publicId: string, current: PlayerSheetDto): PlayerSheetDto | null {
    if (publicId === current.publicId) {
        return withCharacterCount(current);
    }
    const extra = extraPlayerSheets[publicId];
    return extra ? withCharacterCount(extra) : null;
}

export function allPlayerSheets(current: PlayerSheetDto = mockPlayerSheet): PlayerSheetDto[] {
    return [withCharacterCount(current), ...Object.values(extraPlayerSheets).map(withCharacterCount)];
}

