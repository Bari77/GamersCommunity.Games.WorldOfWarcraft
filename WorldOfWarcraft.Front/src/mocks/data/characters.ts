function character(opts: {
    id: string;
    player: string;
    pseudo: string;
    level: number;
    ilvl: number;
    achievement: number;
    sentence?: string | null;
    main?: boolean;
    created: string;
    race: [number, string];
    server: [number, string];
    direction: [number, string];
    alignment: [number, string];
    klass: [number, string];
    mainSpec: [number, string];
    offSpec?: [number, string];
    guild?: GuildBind;
}): CharacterDto {
    return {
        publicId: opts.id,
        playerPublicId: owner(opts.player),
        pseudo: opts.pseudo,
        level: opts.level,
        ilvl: opts.ilvl,
        achievement: opts.achievement,
        sentence: opts.sentence ?? null,
        main: opts.main ?? false,
        creationDate: new Date(opts.created).toISOString(),
        idRace: opts.race[0],
        raceName: opts.race[1],
        idServer: opts.server[0],
        serverName: opts.server[1],
        idDirection: opts.direction[0],
        directionName: opts.direction[1],
        idAlignment: opts.alignment[0],
        alignmentName: opts.alignment[1],
        idClass: opts.klass[0],
        className: opts.klass[1],
        idMainSpecializationClass: opts.mainSpec[0],
        mainSpecializationName: opts.mainSpec[1],
        idSecondarySpecializationClass: opts.offSpec?.[0] ?? null,
        secondarySpecializationName: opts.offSpec?.[1] ?? null,
        guildPublicId: opts.guild?.publicId ?? null,
        guildName: opts.guild?.entitled ?? null,
        guildDiscriminator: opts.guild?.discriminator ?? null,
        guildRank: opts.guild?.rank ?? null,
        guildCrest: opts.guild?.crest,
    };
}

